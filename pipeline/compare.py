"""GLDAS against ERA5-Land snow, per hindcast winter: a report, never an input to the score."""
import csv
import json
import statistics
import sys
from datetime import date
from pathlib import Path

from pipeline import indicators
from pipeline.era5 import load_era5
from pipeline.export import SITE
from pipeline.gldas import OUT as GLDAS_CSV, load_series
from pipeline.nso import load_livestock
from pipeline.score import risk
from pipeline.validate import mortality, spearman

OUT = Path("data/derived/snow_comparison.json")
PAGE = Path("docs/research/snow-comparison.md")


def _r(v: float | None) -> float | None:
    return None if v is None else round(v, 3)


def compare(winters: list[int]) -> dict:
    """Per winter: do the two products rank soums' deepest snow alike, how deep each says it was, and how well the
    score ranks losses with each one's snow z. The GLDAS score is a counterfactual recomputed here, never written."""
    era5, gldas, herds = load_era5(), load_series(GLDAS_CSV), load_livestock()
    out, pool_e, pool_g, pool_m = [], [], [], []
    for y in winters:
        as_of = date(y + 1, 3, 31)
        with indicators.out_path(y).open() as f:
            rows = [r for r in csv.DictReader(f) if r["risk"]]
        depth = [(indicators.snow(era5.get(r["pcode"], {}).get("sde", {}), y, as_of),
                  indicators.snow(gldas.get(r["pcode"], {}), y, as_of)) for r in rows]
        depth = [(e, g) for e, g in depth if e is not None and g is not None]
        re_, rg, ms = [], [], []
        for r in rows:
            m = mortality(herds, r["pcode"], y)
            if m is None or not r["z_snow_gldas"]:
                continue
            z = {k: float(r[f"z_{k}"]) if r[f"z_{k}"] else None for k in ("cold", "snow", "summer", "pressure")}
            re_.append(float(r["risk"]))
            rg.append(risk({**z, "snow": float(r["z_snow_gldas"])}))
            ms.append(m)
        pool_e += re_
        pool_g += rg
        pool_m += ms
        out.append({
            "winter": f"{y}/{(y + 1) % 100:02d}", "n_soums": len(depth),
            "rho_depth": _r(spearman(*map(list, zip(*depth)))) if depth else None,
            "median_era5_m": _r(statistics.median(e for e, _ in depth)) if depth else None,
            "median_gldas_m": _r(statistics.median(g for _, g in depth)) if depth else None,
            "n": len(ms), "rho_soum_era5": _r(spearman(re_, ms)), "rho_soum_gldas": _r(spearman(rg, ms)),
        })
    return {"winters": out,
            "pooled": {"n": len(pool_m), "rho_era5": _r(spearman(pool_e, pool_m)), "rho_gldas": _r(spearman(pool_g, pool_m))}}


def render_md(result: dict) -> str:
    def f(v) -> str:
        return "–" if v is None else str(v)
    lines = [
        "# Snow: GLDAS-2.1 against ERA5-Land",
        "",
        "Generated by `pipeline/compare.py` (run by `pipeline.hindcast`); do not edit by hand.",
        "",
        "ERA5-Land is the scoring snow source from v0.3. That source was fixed before this comparison, by data",
        "latency (the spec, §5): GLDAS-2.1 runs about a month behind, ERA5-Land about a week. These numbers report",
        "how the two differ; they did not choose the source and must not be used to tune it.",
        "",
        "Depth is each soum's deepest monthly mean snow, November to March. ρ depth ranks soums by that depth in both",
        "products. ρ ERA5 / ρ GLDAS rank the risk score against adult livestock mortality (Spearman, soums with NSO",
        "soum losses), once with ERA5-Land snow (as scored) and once with GLDAS snow swapped in (counterfactual).",
        "2009/10 has no soum-level losses, so only its depths are compared.",
        "",
        "| Winter | Soums | ρ depth | Median depth ERA5-Land (m) | Median depth GLDAS (m) | n | ρ ERA5 | ρ GLDAS |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for w in result["winters"]:
        lines.append(f"| {w['winter']} | {w['n_soums']} | {f(w['rho_depth'])} | {f(w['median_era5_m'])} | "
                     f"{f(w['median_gldas_m'])} | {w['n']} | {f(w['rho_soum_era5'])} | {f(w['rho_soum_gldas'])} |")
    p = result["pooled"]
    lines += ["", f"Pooled over every soum-winter with losses (n = {p['n']}): ρ ERA5 {f(p['rho_era5'])}, "
                  f"ρ GLDAS {f(p['rho_gldas'])}.", ""]
    return "\n".join(lines)


def main(winters: list[int] | None = None) -> dict:
    if winters is None:
        winters = [int(label[:4]) for label in json.loads((SITE / "winters.json").read_text())]
    result = compare(winters)
    OUT.write_text(json.dumps(result, indent=2, allow_nan=False))
    PAGE.write_text(render_md(result))
    return result


def check() -> None:
    result = {
        "winters": [
            {"winter": "2009/10", "n_soums": 330, "rho_depth": 0.81, "median_era5_m": 0.21, "median_gldas_m": 0.12,
             "n": 0, "rho_soum_era5": None, "rho_soum_gldas": None},
            {"winter": "2023/24", "n_soums": 330, "rho_depth": 0.74, "median_era5_m": 0.25, "median_gldas_m": 0.15,
             "n": 320, "rho_soum_era5": 0.5, "rho_soum_gldas": 0.49},
        ],
        "pooled": {"n": 320, "rho_era5": 0.5, "rho_gldas": 0.49},
    }
    md = render_md(result)
    rows = [l for l in md.splitlines() if l.startswith("| 20")]
    assert [r.split("|")[1].strip() for r in rows] == ["2009/10", "2023/24"], rows
    assert "fixed before this comparison" in md and "–" in rows[0], md
    before = indicators.read_risk(2023)
    compare([2023])
    assert indicators.read_risk(2023) == before, "the comparison changed the score"
    print("compare check: ok")


if __name__ == "__main__":
    check() if "--check" in sys.argv else main()
